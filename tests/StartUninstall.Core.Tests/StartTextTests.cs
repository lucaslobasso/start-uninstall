using StartUninstall;
using Xunit;

namespace StartUninstall.Core.Tests;

public class StartTextTests
{
    [Theory]
    [InlineData("tile-W~{6D809377-6AF0-444B-8957-A3773F02200E}\\Transmission\\transmission-qt.exe", TileKind.Win32, "{6D809377-6AF0-444B-8957-A3773F02200E}\\Transmission\\transmission-qt.exe")]
    [InlineData("W~Microsoft.AutoGenerated.{894D6C25-7B10-A7C3-7238-7C4781D06C57}", TileKind.Win32, "Microsoft.AutoGenerated.{894D6C25-7B10-A7C3-7238-7C4781D06C57}")]
    [InlineData("P~Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", TileKind.Packaged, "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App")]
    [InlineData("tile-P~Microsoft.WindowsCalculator_8wekyb3d8bbwe!App", TileKind.Packaged, "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App")]
    public void ParsesTileIds(string aid, TileKind kind, string aumid)
    {
        var t = StartTile.Parse(aid);
        Assert.Equal(kind, t.Kind);
        Assert.Equal(aumid, t.Aumid);
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("W~")]
    [InlineData("AllAppsButton")]
    [InlineData("tile-")]
    [InlineData("X~foo")]
    public void IgnoresOtherIds(string? aid) => Assert.Equal(TileKind.None, StartTile.Parse(aid).Kind);

    [Theory]
    [InlineData("Uninstall")]
    [InlineData("uninstall")]
    [InlineData(" Desinstalar ")]
    [InlineData("&Uninstall")]
    [InlineData("Désinstaller")]
    public void KnowsUninstall(string name) => Assert.True(StartText.IsUninstall(name));

    [Theory]
    [InlineData("Unpin from Start")]
    [InlineData("Move to front")]
    [InlineData("Open file location")]
    [InlineData("")]
    [InlineData(null)]
    public void OtherMenuItemsAreNotUninstall(string? name) => Assert.False(StartText.IsUninstall(name));

    [Theory]
    [InlineData("Fake Uninstall Test, New", "Fake Uninstall Test")]
    [InlineData("Steam", "Steam")]
    [InlineData(" Dial, New ", "Dial")]
    [InlineData(null, "")]
    public void TileNames(string? name, string expected) => Assert.Equal(expected, StartText.TileName(name));

    [Theory]
    [InlineData("PPNotepad++", " Notepad++, App, Press right to view options", "Notepad++")]
    [InlineData("PPFake Uninstall Test", " Fake Uninstall Test, App", "Fake Uninstall Test")]
    [InlineData("PP\uE000Fake Uninstall Test\uE001", " \uE000Fake Uninstall Test\uE001, App, Press right to view options", "Fake Uninstall Test")]
    [InlineData("PPFake \uE000Uninst\uE001all Test", "", "Fake Uninstall Test")]
    [InlineData("", " Some App, App, Press right to view options", "Some App")]
    [InlineData(null, "Plain", "Plain")]
    public void SearchResultNames(string? aid, string name, string expected) =>
        Assert.Equal(expected, StartText.SearchResultName(aid, name));

    [Fact]
    public void SearchResultFilesHaveNoAppName() =>
        Assert.Null(StartText.SearchResultName("C:\\x\\node.js", " node.js, JSFile, Press right to switch preview"));
}

public class ProductCodeMatchTests
{
    private const string Code = "{A1B2C3D4-0000-4000-8000-000000000001}";

    [Fact]
    public void ProductCodeWinsOverName()
    {
        var m = new UninstallMatcher(new FakeSource(Fx.All));
        var r = m.Match("Something Else Entirely", null, Code);
        Assert.Equal(MatchKind.Exact, r.Kind);
        Assert.Same(Fx.PyLauncher, r.Entry);
    }

    [Fact]
    public void ProductCodeCaseInsensitive()
    {
        var m = new UninstallMatcher(new FakeSource(Fx.All));
        Assert.Same(Fx.PyLauncher, m.Match("x", null, Code.ToLowerInvariant()).Entry);
    }

    [Fact]
    public void UnknownProductCodeFallsBackToName()
    {
        var m = new UninstallMatcher(new FakeSource(Fx.All));
        var r = m.Match("Git", null, "{00000000-0000-0000-0000-000000000000}");
        Assert.Same(Fx.Git, r.Entry);
    }

    [Fact]
    public void EmptyNameStillMatchesByShortcut()
    {
        var m = new UninstallMatcher(new FakeSource(Fx.All));
        var r = m.Match("", "C:\\Program Files\\7-Zip\\7zFM.exe");
        Assert.Same(Fx.SevenZip, r.Entry);
    }

    [Fact]
    public void EmptyNameNoPathIsNoMatch()
    {
        var m = new UninstallMatcher(new FakeSource(Fx.All));
        Assert.Equal(MatchKind.None, m.Match("  ").Kind);
    }

    [Fact]
    public void FakeTestAppShape()
    {
        // the end-to-end test's throwaway app: HKCU key, DisplayIcon = the exe
        var fake = Fx.E("Fake Uninstall Test", "\"C:\\t\\FakeApp\\FakeUninstaller.cmd\"", UninstallHive.CurrentUser,
            loc: "C:\\t\\FakeApp", icon: "C:\\t\\FakeApp\\FakeUninstallTest.exe", key: "FakeUninstallTest");
        var m = new UninstallMatcher(new FakeSource(Fx.All.Append(fake)));
        var r = m.Match("Fake Uninstall Test", "C:\\t\\FakeApp\\FakeUninstallTest.exe");
        Assert.Equal(MatchKind.Exact, r.Kind);
        Assert.Same(fake, r.Entry);
        Assert.Equal(MatchKind.None, m.Match("Fake Mismatch App", "C:\\t\\FakeApp2\\FakeMismatchApp.exe").Kind);
    }
}
